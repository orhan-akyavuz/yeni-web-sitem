create function public.admin_list_submissions(p_problem_id bigint)
returns table (
  id bigint,
  problem_id bigint,
  answer_text text,
  solution_text text,
  is_correct boolean,
  has_explanation boolean,
  score integer,
  submitted_at timestamptz,
  display_name text,
  email text
)
language plpgsql
security definer set search_path = public
as $$
begin
  perform public.assert_admin();
  return query
    select
      s.id,
      s.problem_id,
      s.answer_text,
      s.solution_text,
      s.is_correct,
      s.has_explanation,
      s.score,
      s.submitted_at,
      coalesce(p.display_name, 'Matematikci') as display_name,
      u.email
    from public.submissions s
    join public.profiles p on p.id = s.user_id
    join auth.users u on u.id = s.user_id
    where s.problem_id = p_problem_id
    order by s.submitted_at desc;
end;
$$;

create or replace function public.admin_review_submission(p_problem_id bigint, p_submission_id bigint, p_is_correct boolean, p_has_explanation boolean)
returns integer
language plpgsql
security definer set search_path = public
as $$
declare awarded integer := case when p_is_correct then case when p_has_explanation then 15 else 10 end else 0 end; submission_user uuid;
begin
  perform public.assert_admin();
  update public.submissions set is_correct = p_is_correct, score = awarded where id = p_submission_id and problem_id = p_problem_id returning user_id into submission_user;
  if not found then raise exception using errcode = '22023', message = 'Submission not found'; end if;
  delete from public.score_events where submission_id = p_submission_id;
  if awarded > 0 then insert into public.score_events (user_id, submission_id, event_type, points) values (submission_user, p_submission_id, 'admin_review', awarded); end if;
  return awarded;
end;
$$;

create or replace function public.admin_highlight_submission(p_problem_id bigint, p_submission_id bigint)
returns boolean
language plpgsql
security definer set search_path = public
as $$
begin
  perform public.assert_admin();
  if not exists (select 1 from public.submissions where id = p_submission_id and problem_id = p_problem_id) then
    raise exception using errcode = '22023', message = 'Submission not found';
  end if;
  delete from public.problem_highlights where problem_id = p_problem_id;
  insert into public.problem_highlights (problem_id, submission_id, approved_by) values (p_problem_id, p_submission_id, auth.uid());
  return true;
end;
$$;

