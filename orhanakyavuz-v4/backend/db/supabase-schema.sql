create or replace function public.submit_weekly_problem(
  p_problem_id bigint,
  p_answer text,
  p_solution text default null
)
returns table (submission_id bigint, is_correct boolean, score integer)
language plpgsql
security definer set search_path = public
as $$
declare
  problem_row public.weekly_problems%rowtype;
  correct boolean;
  awarded integer;
  new_submission_id bigint;
  current_week date := date_trunc('week', now())::date;
  previous_week date := date_trunc('week', now())::date - 7;
  old_streak public.streaks%rowtype;
  next_streak integer;
  total_score integer;
begin
  if auth.uid() is null then
    raise exception using errcode = '28000', message = 'Authentication required';
  end if;

  select * into problem_row
  from public.weekly_problems
  where id = p_problem_id
    and status = 'published'
    and published_at <= now()
    and ends_at > now();

  if not found then
    raise exception using errcode = '22023', message = 'Active problem not found';
  end if;

  correct := lower(trim(coalesce(p_answer, ''))) = lower(trim(problem_row.answer_key));
  awarded := case when correct and not exists (
    select 1 from public.submissions
    where problem_id = p_problem_id and user_id = auth.uid() and is_correct
  ) then case when length(trim(coalesce(p_solution, ''))) > 0 then 15 else 10 end else 0 end;

  insert into public.submissions (problem_id, user_id, answer_text, solution_text, is_correct, has_explanation, score)
  values (p_problem_id, auth.uid(), trim(p_answer), nullif(trim(p_solution), ''), correct, length(trim(coalesce(p_solution, ''))) > 0, awarded)
  returning id into new_submission_id;

  if awarded > 0 then
    insert into public.score_events (user_id, submission_id, event_type, points)
    values (auth.uid(), new_submission_id, case when p_solution is null or trim(p_solution) = '' then 'correct_answer' else 'correct_with_explanation' end, awarded);
  end if;

  select * into old_streak from public.streaks where user_id = auth.uid();
  if old_streak.last_participation_week = current_week then
    next_streak := old_streak.current_streak;
  elsif old_streak.last_participation_week = previous_week then
    next_streak := old_streak.current_streak + 1;
  else
    next_streak := 1;
  end if;
  insert into public.streaks (user_id, current_streak, longest_streak, last_participation_week)
  values (auth.uid(), next_streak, greatest(coalesce(old_streak.longest_streak, 0), next_streak), current_week)
  on conflict (user_id) do update set current_streak = excluded.current_streak,
    longest_streak = excluded.longest_streak, last_participation_week = excluded.last_participation_week,
    updated_at = now();

  select coalesce(sum(points), 0) into total_score from public.score_events where user_id = auth.uid();
  insert into public.user_badges (user_id, badge_id)
  select auth.uid(), b.id from public.badges b
  where b.is_active and ((b.criteria_type = 'streak' and next_streak >= b.criteria_value)
    or (b.criteria_type = 'score' and total_score >= b.criteria_value))
  on conflict (user_id, badge_id) do nothing;

  return query select new_submission_id, correct, awarded;
end;
$$;

revoke all on function public.submit_weekly_problem(bigint, text, text) from public;
grant execute on function public.submit_weekly_problem(bigint, text, text) to authenticated;

create or replace function public.get_weekly_leaderboard()
returns table (name text, score bigint, solved_count bigint)
language sql
security definer set search_path = public
as $$
  select coalesce(p.display_name, 'Matematikci') as name,
    coalesce(sum(se.points), 0)::bigint as score,
    count(distinct se.submission_id)::bigint as solved_count
  from public.score_events se
  join public.profiles p on p.id = se.user_id
  group by p.id, p.display_name
  order by score desc, solved_count desc
  limit 10;
$$;

revoke all on function public.get_weekly_leaderboard() from public;
grant execute on function public.get_weekly_leaderboard() to anon, authenticated;

create or replace function public.assert_admin()
returns void
language plpgsql
security definer set search_path = public
as $$
begin
  if auth.uid() is null or not exists (
    select 1 from public.profiles where id = auth.uid() and role = 'admin'
  ) then
    raise exception using errcode = '42501', message = 'Admin role required';
  end if;
end;
$$;

